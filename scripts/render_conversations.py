"""Render the saved agent exchanges (docs/conversations/*.json) as one Markdown transcript.

    python scripts/render_conversations.py [--dir docs/conversations]

Each JSON file is one HTTP exchange with the agent API: `POST /chat` (question, tool calls with
their full results, answer) or `POST /actions/{id}/confirm`. The Markdown shows the question, the
model(s), every tool call with its status, and the answer; the full tool outputs stay in the JSON.
"""

import argparse
import json
from pathlib import Path


def chat(name: str, rec: dict) -> list[str]:
    r = rec["response"]
    lines = [
        f"**User:** {rec['request']['message']}",
        "",
        f"`POST /chat` -> HTTP {rec['http_status']} | request `{r['request_id']}` | "
        f"model `{r['model']}` | {r['steps']} LLM turns | {r['duration_ms'] / 1000:.1f} s",
        "",
    ]
    if r.get("llm_fallbacks"):
        lines += ["Models skipped: " + "; ".join(f"`{f}`" for f in r["llm_fallbacks"]), ""]
    if r["tool_calls"]:
        lines += ["| # | Tool | Arguments | Status | ms |", "|---|---|---|---|---|"]
        for i, c in enumerate(r["tool_calls"], 1):
            args = json.dumps({k: v for k, v in c["arguments"].items() if v is not None})
            status = c["status"] + (f": {c['error']}" if c.get("error") else "")
            lines.append(
                f"| {i} | `{c['tool']}` | `{args}` | {status.replace('|', '/')} | "
                f"{c['duration_ms']:.0f} |"
            )
        lines.append("")
    lines += ["**Agent:**", "", *[f"> {ln}" if ln else ">" for ln in r["answer"].splitlines()]]
    return lines


def confirm(name: str, rec: dict) -> list[str]:
    r = rec["response"]
    res = r.get("result") or {}
    data = json.dumps(res.get("data"))
    return [
        f"**User confirms** `{rec['endpoint']}` -> HTTP {rec['http_status']}, "
        f"action `{r['status']}`, tool `{res.get('tool')}` returned `{res.get('status')}`",
        "",
        f"```json\n{data[:700]}{' ...' if len(data) > 700 else ''}\n```",
    ]


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--dir", type=Path, default=Path("docs/conversations"))
    args = p.parse_args()
    out = [
        "# Agent conversations (exported evidence)",
        "",
        "Generated by `scripts/render_conversations.py` from the JSON files in this folder, each "
        "one real exchange with the agent API. The JSON files contain every tool's full output.",
    ]
    for path in sorted(args.dir.glob("*.json")):
        rec = json.loads(path.read_text(encoding="utf-8"))
        out += ["", f"## {path.stem}", "", f"Source: [{path.name}]({path.name})", ""]
        out += chat(path.stem, rec) if "request" in rec else confirm(path.stem, rec)
    target = args.dir / "transcripts.md"
    target.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
